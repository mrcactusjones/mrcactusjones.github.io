#!/usr/bin/env python3
"""Regenerate TI84GPT/ti_tokens.cpp from the TI-Toolkit token sheet.

You only need this if you want to change how calculator tokens are turned
into text. Get 8X.xml from https://github.com/TI-Toolkit/tokens and run:

    python3 tools/gen_tokens.py path/to/8X.xml > TI84GPT/ti_tokens.cpp
"""
import sys
import xml.etree.ElementTree as ET

MODELS = ("TI-82", "TI-83", "TI-83+", "TI-84+")  # monochrome TI-84 Plus lineage

# Text we want instead of the sheet's "accessible" spelling.
OVERRIDES = {
    0x0A: " rad", 0x0B: " deg", 0x0C: "^-1", 0x0D: "^2", 0x0E: "^T", 0x0F: "^3",
    0x2C: "i", 0x3B: "E", 0xB0: "-", 0xBF: "e^(", 0xC1: "10^(", 0xEB: "L",
    0xF1: " xroot ", 0x7F: "", 0x80: "", 0x81: "",
    0xBB31: "e", 0xBB9A: "'", 0xBB9B: "`", 0xBB9C: ":", 0xBB9D: "¿",
    0xBB9E: "¡", 0xBBA7: "pi", 0xBBAD: "p-hat", 0xBBAF: "F", 0xBBCF: "~",
    0xBBDB: "...", 0xBBDC: " angle ", 0xBBDD: "ß", 0xBBDE: "^x", 0xBBDF: "T",
    0xBBEA: "10", 0xBBEB: "<-", 0xBBEC: "->", 0xBBED: "^", 0xBBEE: "v",
    0xBBF0: "x", 0xBBF1: " integral ", 0xBBF2: "^", 0xBBF3: "v",
    0xBBF4: "sqrt", 0xBBF5: "=",
}
for digit in range(10):
    OVERRIDES[0xBBE0 + digit] = str(digit)  # subscript digits


def english(token):
    best = None
    for version in token.findall("version"):
        if version.find("since/model").text in MODELS:
            lang = [l for l in version.findall("lang") if l.get("code") == "en"][0]
            best = lang.find("accessible").text
    return best


def clean(code, text):
    if code in OVERRIDES:
        return OVERRIDES[code]
    text = text.replace("^^", "^")
    lead = code >> 8
    if lead == 0x62 or lead == 0xEF:
        text = text.strip("[]")
    if lead == 0x5E:
        text = text.strip("{}")
    if text.startswith("|") and len(text) > 1:
        text = text[1:]
    return text


def c_string(text):
    out = []
    for byte in text.encode("utf-8"):
        ch = chr(byte)
        if ch == '"' or ch == "\\":
            out.append("\\" + ch)
        elif byte == 0x0A:
            out.append("\\n")
        elif 0x20 <= byte < 0x7F:
            out.append(ch)
        else:
            out.append("\\%03o" % byte)
    return '"' + "".join(out) + '"'


def main():
    root = ET.parse(sys.argv[1]).getroot()
    single, double = {}, {}
    for child in root:
        if child.tag == "token":
            code = int(child.get("value")[1:], 16)
            text = english(child)
            if text is not None:
                single[code] = clean(code, text)
        elif child.tag == "two-byte":
            lead = int(child.get("value")[1:], 16)
            for token in child:
                code = (lead << 8) | int(token.get("value")[1:], 16)
                text = english(token)
                if text is not None:
                    double[code] = clean(code, text)

    print("// Generated by tools/gen_tokens.py from the TI-Toolkit token sheet")
    print("// (https://github.com/TI-Toolkit/tokens). Do not edit by hand.")
    print('#include "ti_tokens.h"')
    print()
    print("namespace ti {")
    print()
    print("static const char *const kSingle[256] = {")
    for code in range(256):
        text = single.get(code)
        print("    %s,  // %02X" % (c_string(text) if text is not None else "nullptr", code))
    print("};")
    print()
    print("struct TwoByte {")
    print("  uint16_t code;")
    print("  const char *text;")
    print("};")
    print()
    print("static const TwoByte kDouble[] = {")
    for code in sorted(double):
        print("    {0x%04X, %s}," % (code, c_string(double[code])))
    print("};")
    print()
    print("const char *tokenText1(uint8_t token) { return kSingle[token]; }")
    print()
    print("const char *tokenText2(uint16_t token) {")
    print("  int lo = 0, hi = (int)(sizeof(kDouble) / sizeof(kDouble[0])) - 1;")
    print("  while (lo <= hi) {")
    print("    int mid = (lo + hi) / 2;")
    print("    if (kDouble[mid].code == token) return kDouble[mid].text;")
    print("    if (kDouble[mid].code < token) lo = mid + 1;")
    print("    else hi = mid - 1;")
    print("  }")
    print("  return nullptr;")
    print("}")
    print()
    print("}  // namespace ti")


if __name__ == "__main__":
    main()
